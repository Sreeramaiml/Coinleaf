"""Refuse fixture files that were not produced by the demo generator (NFR-9: no real
financial data in tests or fixtures). Used by the pre-commit hook in .githooks/.

Usage: python scripts/check_fixtures.py FILE...   (exit 1 if any file lacks the marker)
"""

from __future__ import annotations

import sys
from pathlib import Path

MARKER = "Synthetic data generated by the finassist demo generator - not a real statement"


def main(paths: list[str]) -> int:
    bad = []
    for p in map(Path, paths):
        try:
            head = p.read_bytes()[:4096].decode("utf-8-sig", errors="ignore")
        except OSError:
            continue
        if MARKER not in head:
            bad.append(str(p))
    for b in bad:
        print(f"refused: {b} does not carry the synthetic-data marker")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
