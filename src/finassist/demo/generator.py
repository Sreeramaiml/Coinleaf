def _month_range(today: date, n: int) -> list[tuple[int, int]]:
    y, m = today.year, today.month
    out = []
    for _ in range(n):
        m -= 1
        if m == 0:
            y, m = y - 1, 12
        out.append((y, m))
    return list(reversed(out))


class _Rng:
    def __init__(self, seed: int) -> None:
        self.r = random.Random(seed)

    def rupees(self, lo: int, hi: int, paise: bool = True) -> int:
        """Random amount in minor units between lo and hi rupees."""
        v = self.r.randint(lo * 100, hi * 100)
        return v if paise else (v // 100) * 100

    def digits(self, n: int) -> str:
        return "".join(str(self.r.randint(0, 9)) for _ in range(n))

    def day(self, y: int, m: int, lo: int = 1, hi: int | None = None) -> date:
        last = calendar.monthrange(y, m)[1]
        return date(y, m, self.r.randint(lo, min(hi or last, last)))


